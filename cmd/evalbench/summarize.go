package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// summarize prints a Markdown table of every recorded run, oldest first.
// The table is generated, never hand-edited, so the README can only quote
// numbers that a run file backs.
func summarize(args []string) {
	fs := flag.NewFlagSet("summarize", flag.ExitOnError)
	fs.Parse(args)
	dirs := fs.Args()
	if len(dirs) == 0 {
		dirs = []string{"bench/runs"}
	}
	fmt.Println("# Benchmark log")
	fmt.Println()
	fmt.Println("Generated by `evalbench summarize` from the JSON records in `bench/runs/`. Every row is one measured pass;")
	fmt.Println("the record file holds the full setup (host, commit, flags, executor config). Do not edit by hand.")
	fmt.Println()
	fmt.Println("Columns: jobs/min counts every job that reached a terminal state (including cache hits) over the run's wall time.")
	fmt.Println("Attempt latency runs from lease grant to result report on the coordinator clock; overhead is attempt latency")
	fmt.Println("minus the executor time the worker measured (gRPC, worker scheduling, Postgres). Cache saved is cached jobs / total jobs.")
	for _, dir := range dirs {
		table(dir)
	}
}

func table(dir string) {
	files, err := filepath.Glob(filepath.Join(dir, "*.json"))
	if err != nil {
		fail(err)
	}
	sort.Strings(files)
	fmt.Println()
	fmt.Printf("## `%s`\n\n", dir)
	if b, err := os.ReadFile(filepath.Join(dir, "NOTES.md")); err == nil {
		fmt.Println(strings.TrimSpace(string(b)))
		fmt.Println()
	}
	fmt.Println("| record | scenario | pass | workers x conc | jobs | executor config | wall s | jobs/min | attempt p50 ms | attempt p95 ms | exec p95 ms | overhead p95 ms | cache saved | executor calls | retries | lease exp. | failed |")
	fmt.Println("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			fail(err)
		}
		var r Record
		if err := json.Unmarshal(b, &r); err != nil {
			fail(fmt.Errorf("%s: %w", f, err))
		}
		s := r.Setup
		var compact bytes.Buffer
		if err := json.Compact(&compact, s.Config); err != nil {
			compact.Write(s.Config)
		}
		cfg := strings.ReplaceAll(compact.String(), "|", "/")
		if s.KillWorkerAt != "" {
			cfg += fmt.Sprintf(" (SIGKILL 1 worker at %s, lease %s)", s.KillWorkerAt, s.Lease)
		}
		for _, p := range r.Passes {
			st := p.Stats
			fmt.Printf("| [%s](%s) | %s | %s | %d x %d | %d | `%s` | %.2f | %.0f | %.1f | %.1f | %.1f | %.2f | %.1f%% | %d | %d | %d | %d |\n",
				strings.TrimSuffix(filepath.Base(f), ".json")[:16], strings.TrimPrefix(f, "bench/"), s.Name, p.Label, s.Workers, s.Concurrency, st.Total, cfg,
				st.WallSeconds, st.JobsPerMinute, st.AttemptP50MS, st.AttemptP95MS, st.ExecP95MS, st.OverheadP95MS,
				st.CacheSaved*100, st.ExecutorCalls, st.Retries, st.LeaseExpirations, st.Failed)
		}
	}
}
